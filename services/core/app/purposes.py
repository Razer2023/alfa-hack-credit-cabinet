def industry_for(okved: str | None) -> Industry | None:
    code = (okved or "").split(" ", 1)[0].strip()
    return next((i for i in INDUSTRIES if code.startswith(i.okved)), None)


def business_purposes(catalog: list[str], okved: str | None) -> dict:
    """Цели каталога в формулировках бизнеса клиента. Нет правил для отрасли — цели как в каталоге."""
    industry = industry_for(okved)
    if industry is None:
        return {"business": None, "items": [{"title": p, "purpose": p} for p in catalog]}
    known = [p for p in industry.goals if p in catalog]
    rest = [p for p in catalog if p not in industry.goals]
    items = [{"title": industry.goals[p], "purpose": p} for p in known] + [{"title": p, "purpose": p} for p in rest]
    return {"business": industry.name, "items": items}
